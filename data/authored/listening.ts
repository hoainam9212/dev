import type { Level, ListeningLesson, Question } from '@nihongo/shared';

type L = [speaker: string, ja: string, vi: string];
type Q = [prompt: string, choices: string[], answer: number];

function lesson(level: Level, n: number, title: string, script: L[], qs: Q[], dictation: string[]): ListeningLesson {
  const id = `l-${level.toLowerCase()}-${String(n).padStart(2, '0')}`;
  return {
    id,
    level,
    title,
    script: script.map(([speaker, ja, vi]) => ({ speaker, ja, vi })),
    questions: qs.map(([prompt, choices, answer], i): Question => ({ id: `${id}-q${i + 1}`, prompt, choices, answer })),
    dictation,
  };
}

